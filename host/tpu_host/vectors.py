"""Test vectors shared with Scala, so both models stay bit-exact.

Run `python -m tpu_host.vectors` (from host/) to regenerate
src/test/resources/ref_vectors.txt; the Scala test RefVectorsSpec checks
tpu.ref.Quant, tpu.ref.RefModel and the CommandDecoder against it, and
tests/test_vectors.py fails if the file is out of date.

One vector per line, fields separated by spaces, matrices row-major:
  Q x scale q                          quantize
  S scale x...                         choose_scale
  P acc requant relu shift y           post_process (requant, relu: 0/1)
  K shift acc...                       choose_shift
  M m k n requant relu shift | a... | b... | c...    matmul_ref
  FM hexframe aAddr bAddr cAddr m k n ldA ldB ldC requant relu shift
  FW hexframe addr data...             WRITE frame (data as signed int8)
  FR hexframe addr count size          READ frame
Floats are written with repr(), which reads back to the same double.
"""

from pathlib import Path

import numpy as np

from . import protocol as p
from .quant import choose_scale, choose_shift, quantize
from .reference import matmul_ref, post_process

VECTORS_PATH = Path(__file__).resolve().parents[2] / "src" / "test" / "resources" / "ref_vectors.txt"


def _f(x) -> str:
    return repr(float(x))


def _ints(xs) -> str:
    return " ".join(str(int(v)) for v in np.asarray(xs).ravel())


def generate(seed: int = 2026) -> str:
    rng = np.random.default_rng(seed)
    lines = ["# Generated by host/tpu_host/vectors.py, do not edit by hand."]

    # quantize: exact halves (round-half-up), saturation, worked example, random
    edges = [0.0, 0.5, -0.5, 1.5, -1.5, 2.5, -2.5, 0.49999999999999994, -0.49999999999999994,
             126.5, -126.5, 127.4, 127.5, -127.5, 128.0, -128.0, 200.0, -1e9]
    cases = [(x, 1.0) for x in edges] + [(x, 0.005) for x in (0.5, -0.2, 0.3, 0.4)]
    cases += [(x, s) for s in (0.1, 0.003, 7.0) for x in (s * 2.5, -s * 2.5, s * 0.5, -s * 0.5)]
    cases += [(float(x), float(s)) for x, s in zip(rng.normal(0, 3, 60), rng.uniform(0.001, 0.2, 60))]
    for x, s in cases:
        lines.append(f"Q {_f(x)} {_f(s)} {int(quantize(x, s))}")

    # choose_scale
    for xs in [np.zeros(3), np.array([-1.0]), np.array([0.5, -0.25]), *[rng.normal(0, 2, 8) for _ in range(5)]]:
        lines.append(f"S {_f(choose_scale(xs))} " + " ".join(_f(x) for x in xs))

    # post_process: around halves and the saturation limits, int32 extremes
    big = (1 << 31) - 1
    accs = [0, 1, -1, 2, -2, 3, -3, 127, -127, 128, -128, 255, -255, 256, -256,
            2800, -2800, 32767, -32768, big, -big - 1] + [int(v) for v in rng.integers(-big - 1, big, 12)]
    for acc in accs:
        for shift in (0, 1, 2, 8, 16, 31):
            for requant in (0, 1):
                for relu in (0, 1):
                    y = int(post_process(acc, bool(requant), bool(relu), shift))
                    lines.append(f"P {acc} {requant} {relu} {shift} {y}")

    # choose_shift
    shift_cases = [[0], [127], [-127], [128], [-128], [255], [-255], [2800], [big], [-big - 1]]
    shift_cases += [list(rng.integers(-(1 << e), 1 << e, 6)) for e in (4, 7, 10, 20, 30)]
    for accs_ in shift_cases:
        lines.append(f"K {choose_shift(accs_)} {_ints(accs_)}")

    # matmul_ref on random int8 matrices (the full int8 range, -128 included)
    for _ in range(30):
        m, k, n = (int(v) for v in rng.integers(1, 9, 3))
        a = rng.integers(-128, 128, (m, k))
        b = rng.integers(-128, 128, (k, n))
        requant, relu = (int(v) for v in rng.integers(0, 2, 2))
        shift = int(rng.integers(0, 20))
        c = matmul_ref(a, b, bool(requant), bool(relu), shift)
        lines.append(f"M {m} {k} {n} {requant} {relu} {shift} | {_ints(a)} | {_ints(b)} | {_ints(c)}")

    # frames as the host sends them, for the CommandDecoder
    for _ in range(8):
        addrs = [int(v) for v in rng.integers(0, 4096, 3)]
        dims = [int(v) for v in rng.integers(0, 1 << 16, 6)]
        requant, relu = (bool(v) for v in rng.integers(0, 2, 2))
        mm = p.Matmul(*addrs, *dims, requant=requant, relu=relu, shift=int(rng.integers(0, 32)))
        lines.append(f"FM {mm.frame().hex()} {_ints(addrs + dims)} {int(requant)} {int(relu)} {mm.shift}")
    for _ in range(4):
        addr = int(rng.integers(0, 4000))
        data = rng.integers(-128, 128, int(rng.integers(0, 10)))
        lines.append(f"FW {p.write_frame(addr, data.astype(np.int8).tobytes()).hex()} {addr} {_ints(data)}".rstrip())
    for addr, count, size in [(0, 3, 4), (17, 2, 1), (4000, 0, 4)]:
        lines.append(f"FR {p.read_frame(addr, count, size).hex()} {addr} {count} {size}")

    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    VECTORS_PATH.write_text(generate(), encoding="utf-8", newline="\n")
    print(f"wrote {VECTORS_PATH}")
